#!/usr/bin/env node
// indexes.mjs — generated index notes, one per configured folder, so every note there has at least
// one real inbound link. A capture pipeline writes notes nobody links to yet (ideas, digests, daily
// notes); a query-based MOC (Dataview, Bases) shows them but creates no link, so they stay orphans
// in the graph and invisible to an agent that follows links. Each index lists its folder by month
// (from `created`, else the file date), optionally sorted by a numeric field such as `score`.
//
// Dry-run by default, --apply to write. A note is rewritten only when its listing changes:
// `created` is kept and `updated` moves only on a real change, so a nightly run leaves git quiet.
// Index notes carry `type: index`; the auditor treats them as entry points, not orphans.
import fs from 'node:fs';
import path from 'node:path';
import {
  parseArgs, resolveVault, loadConfig, walk, parseFrontmatter, atomicWrite, today, localDate, isMain,
} from './lib.mjs';

const HELP = `indexes — generate one index note per folder (by month), so no note stays an orphan

Usage: node indexes.mjs [--vault <path>] [--config <file>] [--apply] [--json]

  --apply   write the index notes (default: dry-run, print what would change)
  --json    machine-readable output

Folders come from config.indexes: [{ "folder": "Ideas", "sortBy": "score" }, ...].
Without it: the journal folder plus "Ideas" and "Digest" when they exist.`;

export const GENERATED_BY = 'nightshift/vault/indexes.mjs';
export const indexName = folder => `Index - ${path.posix.basename(folder.replace(/\\/g, '/'))}`;
export const isIndexFile = rel => /(^|\/)Index - [^/]+\.md$/.test(rel);

/** Folders to index: config.indexes, or the journal plus the pipeline's Ideas and Digest folders. */
export function indexTargets(vault, config) {
  const list = Array.isArray(config.indexes)
    ? config.indexes
    : [{ folder: config.folders.journal }, { folder: 'Ideas', sortBy: 'score' }, { folder: 'Digest' }];
  return list
    .map(t => (typeof t === 'string' ? { folder: t } : t))
    .filter(t => t && t.folder && fs.existsSync(path.join(vault, t.folder)) && fs.statSync(path.join(vault, t.folder)).isDirectory());
}

/** Notes of one folder (recursive, index notes excluded) with their month and sort value. */
export function collect(vault, config, target) {
  const prefix = target.folder.replace(/\\/g, '/').replace(/\/+$/, '') + '/';
  return walk(vault, config)
    .filter(f => f.rel.startsWith(prefix) && !isIndexFile(f.rel))
    .map(f => {
      const fm = parseFrontmatter(fs.readFileSync(f.abs, 'utf8')).fields;
      const name = path.basename(f.rel, '.md');
      const dated = /^\d{4}-\d{2}-\d{2}$/.test(name) ? name : String(fm.created || '');
      const day = /^\d{4}-\d{2}-\d{2}/.test(dated) ? dated.slice(0, 10) : localDate(fs.statSync(f.abs).mtime);
      const raw = target.sortBy ? Number(fm[target.sortBy]) : NaN;
      return { name, month: day.slice(0, 7), day, sort: Number.isFinite(raw) ? raw : null, status: typeof fm.status === 'string' ? fm.status : '' };
    });
}

/** Body of an index note: newest month first; inside a month, highest sort value then name. */
export function renderIndex(target, notes) {
  const byMonth = new Map();
  for (const n of notes) byMonth.set(n.month, [...(byMonth.get(n.month) || []), n]);
  const parts = [`> Generated by \`${GENERATED_BY}\`: the ${notes.length} notes of \`${target.folder}\`, newest month first. Edits here are overwritten.`];
  for (const month of [...byMonth.keys()].sort().reverse()) {
    const items = byMonth.get(month).sort((a, b) => (b.sort ?? -Infinity) - (a.sort ?? -Infinity) || b.day.localeCompare(a.day) || a.name.localeCompare(b.name));
    parts.push(`## ${month} (${items.length})`);
    parts.push(items.map(n => `- ${n.sort !== null ? `**${n.sort}** · ` : ''}[[${n.name}]]${n.status ? ` · _${n.status}_` : ''}`).join('\n'));
  }
  return parts.join('\n\n');
}

function noteText(title, created, updated, body) {
  return `---\ntags:\n  - index\ncreated: ${created}\nupdated: ${updated}\ntype: index\ngenerated_by: ${GENERATED_BY}\n---\n\n# ${title}\n\n${body}\n`;
}

export function generateIndexes(vault, config, { apply = false, now = new Date() } = {}) {
  const day = today(now);
  const results = [];
  for (const target of indexTargets(vault, config)) {
    const notes = collect(vault, config, target);
    if (!notes.length) continue;
    const title = indexName(target.folder);
    const fp = path.join(vault, target.folder, `${title}.md`);
    const old = fs.existsSync(fp) ? fs.readFileSync(fp, 'utf8') : '';
    const fm = parseFrontmatter(old).fields;
    const body = renderIndex(target, notes);
    const created = fm.created || day;
    const unchanged = old && old.replace(/\r\n/g, '\n') === noteText(title, created, fm.updated, body);
    if (!unchanged && apply) atomicWrite(fp, noteText(title, created, day, body));
    results.push({ file: path.relative(vault, fp).replace(/\\/g, '/'), notes: notes.length, changed: !unchanged });
  }
  return { apply, results, changed: results.filter(r => r.changed).length };
}

function main(argv) {
  const { flags } = parseArgs(argv, ['apply', 'json', 'help']);
  if (flags.help) { console.log(HELP); return 0; }
  const vault = resolveVault(flags);
  const res = generateIndexes(vault, loadConfig(vault, flags), { apply: !!flags.apply });
  if (flags.json) console.log(JSON.stringify(res, null, 2));
  else {
    for (const r of res.results) console.log(`${r.changed ? (res.apply ? 'wrote ' : 'would write') : 'unchanged'}  ${r.file} (${r.notes} notes)`);
    console.log(`${res.apply ? 'applied' : 'dry-run'}: ${res.changed} index note(s) ${res.apply ? 'written' : 'to write'}`);
  }
  return 0;
}

if (await isMain(import.meta.url)) {
  try { process.exitCode = main(process.argv.slice(2)); } catch (e) { console.error(`error: ${e.message}`); process.exitCode = 2; }
}
